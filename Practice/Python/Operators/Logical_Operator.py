# Logical Operator

number_one = 3<5
number_two = 4<5 
print (number_one and number_two) # Logical Operator AND

number_one = 3<5
number_two = 10<5 
print (number_one or number_two) # Logical Operator OR

cpu_usage = 70
memory_usage = 50
print(cpu_usage >80 or memory_usage > 80) # Logical Operator OR